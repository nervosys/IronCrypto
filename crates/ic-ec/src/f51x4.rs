//! Four elements of GF(2^255 - 19) at once, on AVX-512 IFMA, and the
//! Edwards-curve operations built on them.
//!
//! # Why
//!
//! The four-limb field in `fe64.rs` is latency-bound inside a point
//! operation: each multiplication is one long carry chain, and a doubling's
//! squarings and multiplications wait on one another. An Edwards point is
//! four coordinates, and its formulas multiply them four at a time -- a
//! doubling is four squarings and then four multiplications, a mixed
//! addition two rounds of four multiplications -- so on a CPU with
//! `VPMADD52LUQ`/`VPMADD52HUQ` (IFMA), which multiply 52-bit limbs in each of
//! four 64-bit lanes, a point operation is two vector multiplications. This
//! is the layout curve25519-dalek's IFMA backend uses, written here
//! independently.
//!
//! # Representation
//!
//! A lane holds an element as five limbs of radix 2^51 (limb `i` weighs
//! `2^(51 i)`). IFMA reads only the low 52 bits of each operand, so every
//! input to a multiplication has limbs below 2^52; that is what [`reduce`]
//! leaves, and every operation here ends with it.
//!
//! The bounds, for inputs with limbs below 2^52: a limb product is below
//! 2^104, split by IFMA into 52-bit low and high halves. Column `k` of the
//! product takes the low halves of the products with `i + j = k` and twice
//! the high halves of those with `i + j = k - 1` (the high half weighs
//! `2^52 = 2 * 2^51` above its column): at most `5 * 2^52 + 10 * 2^52 < 2^56`.
//! Columns 5 to 9 fold onto 0 to 4 times 19 (`2^255 = 19`): below `20 * 2^56
//! < 2^60.4`. One parallel carry pass then leaves limbs below `2^51 + 2^10`,
//! and limb 0 below `2^51 + 19 * 2^10`: under 2^52.
//!
//! Subtraction adds `16p` first, whose limbs are about 2^55, so nothing goes
//! negative for inputs below 2^53.
//!
//! # Constant time
//!
//! Every operation is a fixed sequence of vector instructions, with no
//! branch and no data-dependent address; lane selection is by permutes and
//! blends with constant immediates or by masks. The constant-time table
//! selection blends every entry under a mask.
//!
//! Each operation is one `asm!` block, generated by `scripts/gen_f51x4.py`
//! into `f51x4_kernels`, which reads its inputs from memory and writes its
//! result to memory: field vectors are 20 words here, never vector values in
//! Rust. Written with intrinsics around one-instruction blocks, LLVM moved,
//! spilled and zeroed the blocks' results with `vmovaps` and `vxorps`, which
//! Intel's list of data-operand-independent timing instructions does not
//! name; every instruction in the blocks is on it.
//!
//! # Toolchain
//!
//! The crate's declared minimum Rust predates the stabilisation of the
//! AVX-512 intrinsics and target features, so the kernels are assembly, and
//! support is detected by CPUID and XGETBV (`crate::avx512`) rather than
//! through `is_x86_feature_detected!`.

// The Edwards operations serve the `std` tables' paths and the probes; a
// `no_std` build uses only X25519's ladder from here.
#![cfg_attr(not(any(feature = "std", feature = "ct-probes")), allow(dead_code))]

use core::mem::MaybeUninit;

use crate::f51x4_kernels as k;
use crate::fe64::Fe64;

/// Proof that this CPU runs IFMA on 256-bit vectors, and that the operating
/// system saves the AVX-512 state, so the instructions will not fault.
///
/// Only [`Ifma::get`] makes one. Every operation takes one, which is what
/// makes them safe to call: the unsafe code behind them is reachable only
/// with a token in hand.
#[derive(Clone, Copy)]
pub struct Ifma(());

impl Ifma {
    /// The token, if this CPU and OS support what the code here needs:
    /// AVX2, AVX-512F, AVX-512DQ, AVX-512VL and AVX-512 IFMA, with the OS
    /// saving the
    /// SSE, AVX and AVX-512 register state; and BMI2 and ADX, for the
    /// four-limb field the conversions here use.
    #[inline]
    pub fn get() -> Option<Ifma> {
        // `--cfg ic_no_avx512` reports this false, for measuring the AVX2
        // paths; see `crate::avx512`.
        if crate::avx512::ifma() && crate::fe64::available() {
            Some(Ifma(()))
        } else {
            None
        }
    }
}

/// Four elements: limb `i` of lane `l` at word `4 i + l`. Aligned to 32
/// bytes, though the kernels need no alignment.
#[derive(Clone, Copy)]
#[repr(C, align(32))]
pub struct F4([u64; 20]);

/// An Edwards point `(X : Y : Z : T)`, one coordinate per lane in that
/// order.
#[derive(Clone, Copy)]
#[repr(transparent)]
pub struct P4(F4);

/// The operand of an addition, `(Y - X, Y + X, 2d T, 2 Z)` of the point
/// being added, one per lane in that order: what the formula multiplies the
/// accumulator's `(Y - X, Y + X, T, Z)` by.
#[derive(Clone, Copy)]
#[repr(transparent)]
pub struct N4(F4);

/// Spill space for one kernel, left uninitialised: a kernel writes each word
/// of it before reading it.
type Spill = MaybeUninit<[u64; k::SPILL_WORDS]>;

impl F4 {
    fn ptr(&self) -> *const u64 {
        self.0.as_ptr()
    }
}

/// `o =` the state after one X25519 ladder step, in the form
/// `x25519::ladder_in` documents: the state `(xm, zm, xn, zn)` in lanes, `x1`
/// in every lane, the doubling's input chosen by the secret `swap`, all ones
/// or zero.
///
/// # Safety
///
/// The CPU must have what `Ifma::get` checks.
#[inline]
unsafe fn ladder_step_into(o: &mut MaybeUninit<F4>, state: &F4, x1: &F4, swap: &u64) {
    let mut t = Spill::uninit();
    // SAFETY: each input pointer is a whole field vector, the mask one word,
    // and `o` and `t` are the caller's and this function's own, apart from
    // the inputs; the kernel writes all of `o`.
    unsafe {
        k::ladder_step(
            state.ptr(),
            x1.ptr(),
            swap,
            o.as_mut_ptr().cast(),
            t.as_mut_ptr().cast(),
        )
    }
}

/// `o = p + n`.
///
/// # Safety
///
/// The CPU must have what `Ifma::get` checks.
#[cfg(any(feature = "std", feature = "ct-probes"))]
#[inline]
unsafe fn add_into(o: &mut MaybeUninit<F4>, p: &P4, n: &N4) {
    let mut t = Spill::uninit();
    // SAFETY: as in `ladder_step_into`.
    unsafe {
        k::add(
            p.0.ptr(),
            n.0.ptr(),
            core::ptr::null(),
            o.as_mut_ptr().cast(),
            t.as_mut_ptr().cast(),
        )
    }
}

/// `o = 2 p`.
///
/// # Safety
///
/// The CPU must have what `Ifma::get` checks.
#[cfg(any(feature = "std", feature = "ct-probes"))]
#[inline]
unsafe fn double_into(o: &mut MaybeUninit<F4>, p: &P4) {
    let mut t = Spill::uninit();
    // SAFETY: as in `ladder_step_into`.
    unsafe {
        k::double(
            p.0.ptr(),
            core::ptr::null(),
            core::ptr::null(),
            o.as_mut_ptr().cast(),
            t.as_mut_ptr().cast(),
        )
    }
}

/// The table selection's masks, each all ones or zero, computed without a
/// branch: entry `i`'s where the digit's magnitude is `i + 1`, and the
/// sign's ninth.
#[cfg(any(feature = "std", feature = "ct-probes"))]
fn select_masks(digit: i8) -> [u64; 9] {
    let negative = u64::from((digit as u8) >> 7);
    let magnitude = ((digit as i16 ^ (digit as i16 >> 7)) - (digit as i16 >> 7)) as u64;
    let mut m = [0u64; 9];
    for (i, slot) in m.iter_mut().enumerate().take(8) {
        let hit = (magnitude ^ (i as u64 + 1)).wrapping_sub(1) >> 63;
        *slot = crate::fe64::mask(hit);
    }
    m[8] = crate::fe64::mask(negative);
    m
}

/// `o =` the operand of `digit` times the table's base.
///
/// # Safety
///
/// The CPU must have what `Ifma::get` checks.
#[cfg(any(feature = "std", feature = "ct-probes"))]
#[inline]
unsafe fn select_into(o: &mut MaybeUninit<F4>, table: &[N4; 8], digit: i8) {
    let masks = select_masks(digit);
    let mut t = Spill::uninit();
    // SAFETY: `N4` is a transparent `F4`, 20 words, so the table is 160
    // contiguous words; the masks are nine words.
    unsafe {
        k::select(
            table.as_ptr().cast(),
            core::ptr::null(),
            masks.as_ptr(),
            o.as_mut_ptr().cast(),
            t.as_mut_ptr().cast(),
        )
    }
}

/// X25519 on the four-lane ladder.
///
/// # Safety
///
/// The CPU must have what `Ifma::get` checks.
unsafe fn x25519_impl(scalar: &[u8; 32], u: &[u8; 32]) -> [u8; 32] {
    let x1 = Fe64::from_bytes(u);
    let x14 = pack([&x1, &x1, &x1, &x1]);
    // The RFC's initial state: (x2, z2) = (1, 0) in n, (x3, z3) = (u, 1) in
    // m. Two buffers, written in turn, so that the state is never copied.
    let mut state = [
        MaybeUninit::new(pack([&x1, &Fe64::ONE, &Fe64::ONE, &Fe64::ZERO])),
        MaybeUninit::uninit(),
    ];
    let mut cur = 0;
    let mut prev = 0u64;
    for pos in (0..255).rev() {
        let bit = u64::from((scalar[pos / 8] >> (pos & 7)) & 1);
        let swap = crate::fe64::mask(bit ^ prev);
        let [s0, s1] = &mut state;
        let (from, to) = if cur == 0 { (s0, s1) } else { (s1, s0) };
        // SAFETY: `from` holds the state, the initial one or the last step's
        // output; the CPU is as this function requires.
        unsafe { ladder_step_into(to, from.assume_init_ref(), &x14, &swap) };
        cur ^= 1;
        prev = bit;
    }
    // SAFETY: the last step wrote `state[cur]`.
    let [xm, zm, xn, zn] = unpack(unsafe { state[cur].assume_init_ref() });
    // The RFC's last swap: its (x2, z2) is n, or m when the final flag is set.
    let m = crate::fe64::mask(prev);
    let x = Fe64::select_mask(&xn, &xm, m);
    let z = Fe64::select_mask(&zn, &zm, m);
    x.mul(&z.invert()).to_bytes()
}

impl Ifma {
    /// X25519's ladder, `scalar * u`, four lanes at a time: the
    /// `x25519::ladder_in` step with its three rounds of multiplications
    /// done four at once.
    pub fn x25519_ladder(self, scalar: &[u8; 32], u: &[u8; 32]) -> [u8; 32] {
        // SAFETY: the token exists only where `get` found the features.
        unsafe { x25519_impl(scalar, u) }
    }
}

/// Four elements into lanes.
fn pack(e: [&Fe64; 4]) -> F4 {
    let mut r = [0u64; 20];
    for (l, x) in e.iter().enumerate() {
        let limbs = to_limbs51(x);
        for i in 0..5 {
            r[4 * i + l] = limbs[i];
        }
    }
    F4(r)
}

/// Lanes back to four elements.
fn unpack(a: &F4) -> [Fe64; 4] {
    core::array::from_fn(|l| Fe64::from_limbs51(core::array::from_fn(|i| a.0[4 * i + l])))
}

/// Split four 64-bit limbs into five of 51 bits; the top one takes the last
/// 52 bits, so any 256-bit value fits below 2^52 per limb.
fn to_limbs51(x: &Fe64) -> [u64; 5] {
    let w = x.0;
    let m = (1u64 << 51) - 1;
    [
        w[0] & m,
        ((w[0] >> 51) | (w[1] << 13)) & m,
        ((w[1] >> 38) | (w[2] << 26)) & m,
        ((w[2] >> 25) | (w[3] << 39)) & m,
        w[3] >> 12,
    ]
}

impl Ifma {
    /// The point `(X : Y : Z : T)`.
    #[inline]
    pub fn point(self, x: &Fe64, y: &Fe64, z: &Fe64, t: &Fe64) -> P4 {
        P4(pack([x, y, z, t]))
    }

    /// `(X, Y, Z, T)` of a point.
    #[inline]
    pub fn coordinates(self, p: &P4) -> [Fe64; 4] {
        unpack(&p.0)
    }

    /// The operand for adding the point with these `(Y - X, Y + X, 2d T,
    /// 2 Z)`.
    #[inline]
    pub fn operand(self, ymx: &Fe64, ypx: &Fe64, t2d: &Fe64, z2: &Fe64) -> N4 {
        N4(pack([ymx, ypx, t2d, z2]))
    }

    /// `2 P`, in extended coordinates.
    #[cfg(any(feature = "std", feature = "ct-probes"))]
    #[inline]
    pub fn double(self, p: &P4) -> P4 {
        let mut o = MaybeUninit::uninit();
        // SAFETY: the token exists only where `get` found the features; the
        // kernel writes all of `o`.
        unsafe {
            double_into(&mut o, p);
            P4(o.assume_init())
        }
    }

    /// `P + N`, in extended coordinates.
    #[cfg(any(feature = "std", feature = "ct-probes"))]
    #[inline]
    pub fn add(self, p: &P4, n: &N4) -> P4 {
        let mut o = MaybeUninit::uninit();
        // SAFETY: as in `double`.
        unsafe {
            add_into(&mut o, p, n);
            P4(o.assume_init())
        }
    }

    /// The operand of `-N`.
    #[cfg(feature = "std")]
    #[inline]
    pub fn negate(self, n: &N4) -> N4 {
        let mut o = MaybeUninit::<F4>::uninit();
        let mut t = Spill::uninit();
        // SAFETY: as in `double`.
        unsafe {
            k::negate(
                n.0.ptr(),
                core::ptr::null(),
                core::ptr::null(),
                o.as_mut_ptr().cast(),
                t.as_mut_ptr().cast(),
            );
            N4(o.assume_init())
        }
    }

    /// `digit * base` for `digit` in `[-8, 8]`, from the operands of `1..=8`
    /// times `base`, in constant time: every entry is read and blended under
    /// a mask, and the sign applied the same way.
    #[cfg(any(feature = "std", feature = "ct-probes"))]
    #[inline]
    pub fn select(self, table: &[N4; 8], digit: i8) -> N4 {
        let mut o = MaybeUninit::uninit();
        // SAFETY: as in `double`.
        unsafe {
            select_into(&mut o, table, digit);
            N4(o.assume_init())
        }
    }

    /// Lane-wise `a * b`, for the tests.
    #[cfg(test)]
    fn mul4(self, a: [&Fe64; 4], b: [&Fe64; 4]) -> [Fe64; 4] {
        let (a, b) = (pack(a), pack(b));
        let mut o = MaybeUninit::<F4>::uninit();
        let mut t = Spill::uninit();
        // SAFETY: as in `double`.
        unsafe {
            k::mul(
                a.ptr(),
                b.ptr(),
                core::ptr::null(),
                o.as_mut_ptr().cast(),
                t.as_mut_ptr().cast(),
            );
            unpack(o.assume_init_ref())
        }
    }

    /// Lane-wise `a^2`, for the tests.
    #[cfg(test)]
    fn square4(self, a: [&Fe64; 4]) -> [Fe64; 4] {
        let a = pack(a);
        let mut o = MaybeUninit::<F4>::uninit();
        let mut t = Spill::uninit();
        // SAFETY: as in `double`.
        unsafe {
            k::square(
                a.ptr(),
                core::ptr::null(),
                core::ptr::null(),
                o.as_mut_ptr().cast(),
                t.as_mut_ptr().cast(),
            );
            unpack(o.assume_init_ref())
        }
    }
}

/// The four-lane operations for `scripts/ct-audit` to read compiled; behind
/// the `ct-probes` feature, not API.
#[cfg(feature = "ct-probes")]
#[doc(hidden)]
pub mod probes {
    use super::*;

    /// Four elements as `[u64; 4]` limbs, as the probes pass them.
    pub type Lanes = [[u64; 4]; 4];

    fn load(x: &Lanes) -> F4 {
        let e = x.map(Fe64);
        pack([&e[0], &e[1], &e[2], &e[3]])
    }

    fn store(a: &F4) -> Lanes {
        unpack(a).map(|e| e.0)
    }

    /// One X25519 ladder step on four lanes.
    ///
    /// # Safety
    ///
    /// Only on a CPU `Ifma::get` accepts.
    pub unsafe fn ladder_step(state: &Lanes, x1: &[u64; 4], swap: u64) -> Lanes {
        let x1 = Fe64(*x1);
        let mask = crate::fe64::mask(swap & 1);
        let mut o = MaybeUninit::uninit();
        // SAFETY: as the caller guarantees.
        unsafe {
            ladder_step_into(&mut o, &load(state), &pack([&x1, &x1, &x1, &x1]), &mask);
            store(o.assume_init_ref())
        }
    }

    /// The constant-time table selection.
    ///
    /// # Safety
    ///
    /// As [`ladder_step`].
    pub unsafe fn select(table: &[Lanes; 8], digit: i8) -> Lanes {
        // Built in place: an array returned by value is moved with memcpy,
        // a call out of the probe. Written out rather than looped, as the
        // compiler keeps a loop here and check-ct.py allows no branch.
        let mut t = MaybeUninit::<[N4; 8]>::uninit();
        let p = t.as_mut_ptr().cast::<N4>();
        macro_rules! put {
            ($($i:literal)*) => {$(
                // SAFETY: `$i < 8`, inside the array.
                unsafe { p.add($i).write(N4(load(&table[$i]))) };
            )*};
        }
        put!(0 1 2 3 4 5 6 7);
        let mut o = MaybeUninit::uninit();
        // SAFETY: every entry is written above; as the caller guarantees.
        unsafe {
            select_into(&mut o, t.assume_init_ref(), digit);
            store(o.assume_init_ref())
        }
    }

    /// A mixed addition.
    ///
    /// # Safety
    ///
    /// As [`ladder_step`].
    pub unsafe fn add(p: &Lanes, n: &Lanes) -> Lanes {
        let mut o = MaybeUninit::uninit();
        // SAFETY: as the caller guarantees.
        unsafe {
            add_into(&mut o, &P4(load(p)), &N4(load(n)));
            store(o.assume_init_ref())
        }
    }

    /// A doubling.
    ///
    /// # Safety
    ///
    /// As [`ladder_step`].
    pub unsafe fn double(p: &Lanes) -> Lanes {
        let mut o = MaybeUninit::uninit();
        // SAFETY: as the caller guarantees.
        unsafe {
            double_into(&mut o, &P4(load(p)));
            store(o.assume_init_ref())
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn token() -> Option<Ifma> {
        let t = Ifma::get();
        if t.is_none() {
            std::eprintln!("f51x4: no AVX-512 IFMA here; four-lane field not exercised");
        }
        t
    }

    struct Rng(u64);
    impl Rng {
        fn next(&mut self) -> u64 {
            self.0 ^= self.0 >> 12;
            self.0 ^= self.0 << 25;
            self.0 ^= self.0 >> 27;
            self.0.wrapping_mul(0x2545_f491_4f6c_dd1d)
        }
        fn fe(&mut self) -> Fe64 {
            let pick = |r: u64, n: u64| match r % 6 {
                0 => u64::MAX,
                1 => 0,
                2 => u64::MAX - (n % 64),
                _ => n,
            };
            Fe64(core::array::from_fn(|_| {
                let (r, n) = (self.next(), self.next());
                pick(r, n)
            }))
        }
    }

    #[test]
    fn the_four_lane_field_agrees_with_the_four_limb_one() {
        let Some(t) = token() else { return };
        let mut rng = Rng(0x1357_9bdf_2468_ace0);
        let n = if cfg!(debug_assertions) {
            20_000
        } else {
            400_000
        };
        for _ in 0..n {
            let a: [Fe64; 4] = core::array::from_fn(|_| rng.fe());
            let b: [Fe64; 4] = core::array::from_fn(|_| rng.fe());
            let ar = [&a[0], &a[1], &a[2], &a[3]];
            let br = [&b[0], &b[1], &b[2], &b[3]];
            let got = t.mul4(ar, br);
            let sq = t.square4(ar);
            for l in 0..4 {
                assert_eq!(
                    got[l].to_bytes(),
                    a[l].mul(&b[l]).to_bytes(),
                    "mul lane {l}"
                );
                assert_eq!(
                    sq[l].to_bytes(),
                    a[l].square().to_bytes(),
                    "square lane {l}"
                );
            }
            // And a product of products, so outputs are tested as inputs.
            let again = t.mul4(
                [&got[0], &got[1], &got[2], &got[3]],
                [&sq[0], &sq[1], &sq[2], &sq[3]],
            );
            for l in 0..4 {
                assert_eq!(
                    again[l].to_bytes(),
                    a[l].mul(&b[l]).mul(&a[l].square()).to_bytes(),
                    "chained lane {l}"
                );
            }
        }
    }

    #[test]
    #[ignore = "diagnostic"]
    fn vector_mul_costs() {
        use std::time::Instant;
        let Some(t) = token() else { return };
        let a: [Fe64; 4] = core::array::from_fn(|i| Fe64([i as u64 + 3, 5, 7, 11]));
        let n = 1_000_000u32;
        let run = |label: &str, f: &mut dyn FnMut()| {
            let mut best = f64::INFINITY;
            for _ in 0..7 {
                let s = Instant::now();
                f();
                best = best.min(s.elapsed().as_secs_f64() / n as f64 * 1e9);
            }
            std::println!("{label:<28} {best:.2} ns");
        };
        let r = [&a[0], &a[1], &a[2], &a[3]];
        let mut y = a;
        run("mul4 chain (latency)", &mut || {
            for _ in 0..n {
                y = t.mul4([&y[0], &y[1], &y[2], &y[3]], r);
            }
        });
        run("square4 chain (latency)", &mut || {
            for _ in 0..n {
                y = t.square4([&y[0], &y[1], &y[2], &y[3]]);
            }
        });
        core::hint::black_box(y);
    }

    #[test]
    fn packing_round_trips() {
        let Some(t) = token() else { return };
        let mut rng = Rng(42);
        for _ in 0..10_000 {
            let a: [Fe64; 4] = core::array::from_fn(|_| rng.fe());
            let p = t.point(&a[0], &a[1], &a[2], &a[3]);
            let back = t.coordinates(&p);
            for l in 0..4 {
                assert_eq!(back[l].to_bytes(), a[l].to_bytes());
            }
        }
    }
}
