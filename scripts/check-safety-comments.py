#!/usr/bin/env python3
"""Fail if an `unsafe` block or `unsafe fn` lacks its safety documentation.

The repository's rule (AGENTS.md) is that every `unsafe` block states, in a
`// SAFETY:` comment, the precondition its caller has to uphold, and every
`unsafe fn` documents that precondition in a `/// # Safety` section. This
checks that mechanically; it cannot check that the comment is correct, which
still takes a reader.

A block passes when `SAFETY:` appears on the `unsafe` line, within the three
lines above it, or in the contiguous comment block directly above it. An
`unsafe fn` passes when `# Safety` appears in the contiguous doc-comment block
above it, attributes allowed in between.

Usage: scripts/check-safety-comments.py [paths...]
With no arguments every tracked `.rs` file is checked. Exits 1 on any
violation, listing each one as path:line.
"""

import os
import re
import subprocess
import sys

# Generated by scripts/gen_*.py. Their text is out of scope for hand edits, so
# a finding there could not be fixed by the person reading it.
GENERATED = {
    "crates/ic-ec/src/nist/p256_x86_point.rs",
    "crates/ic-ec/src/nist/p384_x86_point.rs",
    "crates/ic-ec/src/nist/mont_x86.rs",
    "crates/ic-ec/src/nist/ifma_kernels.rs",
}

UNSAFE_BLOCK = re.compile(r"\bunsafe\s*\{")
UNSAFE_FN = re.compile(r'\bunsafe\s+(?:extern\s+"[^"]*"\s+)?fn\s+\w')
ATTRIBUTE = re.compile(r"^\s*#\[")


def is_comment(line):
    return line.strip().startswith("//")


def code_part(line):
    """The line with a trailing `//` comment removed. String literals that
    contain `//` before an `unsafe` are rare enough that a plain cut is used."""
    if is_comment(line):
        return ""
    return line.split("//", 1)[0]


def comment_block_above(lines, i):
    """Yield the text of the contiguous comment and attribute lines above line i."""
    j = i - 1
    while j >= 0 and (is_comment(lines[j]) or ATTRIBUTE.match(lines[j])):
        yield lines[j]
        j -= 1


def check_block(lines, i):
    """An unsafe block at line i (0-based) needs SAFETY: on it, near it, or above."""
    if "SAFETY:" in lines[i]:
        return True
    for k in range(max(0, i - 3), i):
        if "SAFETY:" in lines[k]:
            return True
    return any("SAFETY:" in text for text in comment_block_above(lines, i))


def check_fn(lines, i):
    """An unsafe fn at line i (0-based) needs `# Safety` in its doc block."""
    return any("# Safety" in text for text in comment_block_above(lines, i))


def violations(path):
    with open(path, encoding="utf-8") as f:
        lines = f.read().split("\n")
    found = []
    for i, line in enumerate(lines):
        code = code_part(line)
        if UNSAFE_FN.search(code):
            if not check_fn(lines, i):
                found.append((i + 1, "unsafe fn without a `# Safety` doc section"))
        elif UNSAFE_BLOCK.search(code):
            if not check_block(lines, i):
                found.append((i + 1, "unsafe block without a `// SAFETY:` comment"))
    return found


def repo_root():
    return subprocess.run(
        ["git", "rev-parse", "--show-toplevel"],
        capture_output=True, text=True, check=True,
    ).stdout.strip()


def tracked_rust_files(root):
    out = subprocess.run(
        ["git", "ls-files", "*.rs"], cwd=root, check=True,
        capture_output=True, text=True,
    ).stdout
    return [p for p in out.split("\n") if p]


def main(argv):
    root = repo_root()
    if argv:
        files = [
            os.path.relpath(os.path.abspath(a), root).replace(os.sep, "/")
            for a in argv
        ]
    else:
        files = tracked_rust_files(root)

    bad = 0
    checked = 0
    for rel in files:
        if rel in GENERATED or rel.startswith(".claude/"):
            continue
        path = os.path.join(root, rel)
        if not os.path.isfile(path):
            continue
        checked += 1
        for lineno, message in violations(path):
            print(f"{rel}:{lineno}: {message}")
            bad += 1

    if bad:
        print(f"\n{bad} unsafe site(s) without safety documentation", file=sys.stderr)
        return 1
    print(f"safety comments: {checked} files, every unsafe block and fn documented")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
