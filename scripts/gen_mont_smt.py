#!/usr/bin/env python3
"""Generate the SMT-LIB files for the Montgomery multiplication (CIOS) at N words.

usage: gen_mont_smt.py N outdir
"""
import sys, os

N = int(sys.argv[1])
out = sys.argv[2]
W = 2 ** 64


def w(k):
    return str(W ** k)


def decl(names):
    return "\n".join(f"(declare-const {n} Int)" for n in names)


a = [f"a{i}" for i in range(N)]
b = [f"b{i}" for i in range(N)]
m = [f"m{i}" for i in range(N)]
u = [f"u{i}" for i in range(N)]
t = [f"t{i}" for i in range(N + 1)]


def poly(names):
    return "(+ " + " ".join(names[0:1] + [f"(* {n} {w(k)})" for k, n in enumerate(names) if k > 0]) + ")"


def terms(x, y, wrong=False):
    # sum_{i,j} x_j y_i 2^(64 (i + j)): x indexed by column j, y by row i
    ts = []
    for i in range(N):
        for j in range(N):
            k = i + j
            if wrong and i == 1 and j == 2:
                k += 1
            ts.append(f"(* {x[j]} {y[i]} {w(k)})")
    return "(+ " + " ".join(ts) + ")"


head = f"""; Montgomery multiplication (CIOS) at {N} words, over the integers.
;
; Generated by gen_mont_smt.py {N}; do not edit by hand. A statement about
; polynomials and about inequalities, not about the code: see docs/PROOFS.md,
; "P-384 multiplication". Kani proves (arith/proofs.rs), for every product
; value p_ij <= (2^64 - 1)^2 and every digit u_i,
;
;   2^(64 N) T + sum_i l_i 2^(64 i) = sum_(i,j) pa_ij 2^(64 (i + j)) + sum_(i,j) pm_ij 2^(64 (i + j))
;
; and the digit lemma gives l_i = 0. With pa_ij = a_j b_i and pm_ij = u_i m_j,
; the facts below are what turn that into T = (a b + U m) / 2^(64 N) < 2 m.
;
; The negation of the claim is asserted; `unsat` proves it.

(set-logic QF_NIA)
{decl(a + b + m + u + t)}
"""

words = "(and " + " ".join(f"(and (<= 0 {n}) (< {n} {W}))" for n in a + b + m + u + t) + ")"
defs = f"""
(define-fun A () Int {poly(a)})
(define-fun B () Int {poly(b)})
(define-fun M () Int {poly(m)})
(define-fun U () Int {poly(u)})
(define-fun T () Int {poly(t)})
(define-fun SA () Int {terms(a, b)})
(define-fun SM () Int {terms(u, m)})
"""

files = {}

# 1. The identity: the weighted sum of the products is a b + U m.
files["mont-identity.smt2"] = (
    head + defs + "\n(assert (not (= (+ SA SM) (+ (* A B) (* U M)))))\n(check-sat)\n",
    "unsat",
)

# 1b. Negative control: one product at the wrong weight.
defs_wrong = defs.replace(f"(define-fun SA () Int {terms(a, b)})", f"(define-fun SA () Int {terms(a, b, wrong=True)})")
files["mont-identity-wrong-weight.smt2"] = (
    head + defs_wrong + "\n(assert (not (= (+ SA SM) (+ (* A B) (* U M)))))\n(check-sat)\n",
    "sat",
)

# 2. The bound: 2^(64 N) T = a b + U m, a and b below m, digits words: T < 2 m.
bound = f"""
(assert {words})
(assert (= (* {w(N)} T) (+ (* A B) (* U M))))
(assert (< A M))
(assert (< B M))
(assert (not (< T (* 2 M))))
(check-sat)
"""
files["mont-bound.smt2"] = (head + defs + bound, "unsat")

# 2b. Negative control: neither a nor b below m; T < 2 m can fail.
bound_nob = bound.replace("(assert (< A M))\n", "").replace("(assert (< B M))\n", "")
files["mont-bound-unbounded.smt2"] = (head + defs + bound_nob, "sat")

# 3. The congruence: if out is T or T - m, then 2^(64 N) out - a b is a multiple
# of m, with the multiplier U or U - 2^(64 N): 2^(64 N) out = a b mod m.
cong = f"""
(assert {words})
(assert (= (* {w(N)} T) (+ (* A B) (* U M))))
(declare-const OUT Int)
(assert (or (= OUT T) (= OUT (- T M))))
(assert (not (or (= (- (* {w(N)} OUT) (* A B)) (* U M))
                 (= (- (* {w(N)} OUT) (* A B)) (* (- U {w(N)}) M)))))
(check-sat)
"""
files["mont-congruence.smt2"] = (head + defs + cong, "unsat")

# 4. The rows: N rows, each a multiplication phase and a reduction phase,
# telescope. The relations are those the Kani phase harnesses prove of the
# code (arith/proofs.rs, `mul_identity` and `reduce_identity`), over products
# pa_i_j and pm_i_j that are variables here:
#
#   T'_i = T_i + sum_j pa_i_j 2^(64 j)
#   2^64 T_(i+1) + l_i = T'_i + sum_j pm_i_j 2^(64 j)
#
# and the claim is the sum Kani's `cios_sums_its_products` used to state in one
# formula: 2^(64 N) T_N + sum_i l_i 2^(64 i) = sum_(i,j) (pa_ij + pm_ij) 2^(64 (i + j)).
rows_decl = []
rows_asserts = []
rhs = []
lhs_drop = []
for i in range(N):
    for j in range(N):
        rows_decl += [f"pa_{i}_{j}", f"pm_{i}_{j}"]
    rows_decl += [f"l_{i}", f"T{i + 1}", f"X{i}"]  # X_i = T'_i
for i in range(N):
    ti = "0" if i == 0 else f"T{i}"
    pa = "(+ " + " ".join(f"(* pa_{i}_{j} {w(j)})" for j in range(N)) + ")"
    pm = "(+ " + " ".join(f"(* pm_{i}_{j} {w(j)})" for j in range(N)) + ")"
    rows_asserts.append(f"(assert (= X{i} (+ {ti} {pa})))")
    rows_asserts.append(f"(assert (= (+ (* {w(1)} T{i + 1}) l_{i}) (+ X{i} {pm})))")
    for j in range(N):
        rhs.append(f"(* (+ pa_{i}_{j} pm_{i}_{j}) {w(i + j)})")
    lhs_drop.append(f"(* l_{i} {w(i)})")
rows = (
    head.split("(set-logic")[0]
    + "(set-logic QF_NIA)\n"
    + decl(rows_decl)
    + "\n"
    + "\n".join(rows_asserts)
    + f"\n(assert (not (= (+ (* {w(N)} T{N}) {' '.join(['(+'] + lhs_drop)}) )"
    + f" (+ {' '.join(rhs)}))))\n(check-sat)\n"
)
files["mont-rows.smt2"] = (rows, "unsat")
# 4b. Negative control: the claim without the dropped words is false.
rows_nodrop = rows.replace(f"(+ (* {w(N)} T{N}) {' '.join(['(+'] + lhs_drop)}) )", f"(* {w(N)} T{N})")
assert rows_nodrop != rows
files["mont-rows-without-dropped-words.smt2"] = (rows_nodrop, "sat")

os.makedirs(out, exist_ok=True)
for name, (text, want) in files.items():
    with open(os.path.join(out, name), "w", newline="\n") as f:
        f.write(text)
    print(name, want)
