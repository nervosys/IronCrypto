"""Compute Blowfish's initial P-array and S-boxes from the digits of pi.

    python -I scripts/gen_blowfish_tables.py > crates/ic-kdf/src/bcrypt/tables.rs

Blowfish initialises its 18 P-array words and four 256-word S-boxes, 1042
words in order, with the fractional part of pi in hexadecimal: P[0] is
0x243F6A88, the first eight hex digits after the point. Schneier's paper
says so, and gives the first words of each table, which this script checks.

Pi is computed here, not copied: Machin's formula,
pi = 16 arctan(1/5) - 4 arctan(1/239), in integer arithmetic scaled by
2^(32 * 1042 + 64), so the 1042 words are exact. Nothing else is involved.
"""

WORDS = 18 + 4 * 256
GUARD = 64
SCALE = 32 * WORDS + GUARD


def arctan_inverse(x, one):
    """arctan(1/x) * one, by its Taylor series in integers."""
    total = term = one // x
    x2, n, sign = x * x, 1, -1
    while term:
        term //= x2
        n += 2
        total += sign * (term // n)
        sign = -sign
    return total


def main():
    one = 1 << SCALE
    pi = 16 * arctan_inverse(5, one) - 4 * arctan_inverse(239, one)
    frac = (pi - 3 * one) >> GUARD  # 32 * WORDS bits of the fractional part
    words = [(frac >> (32 * (WORDS - 1 - i))) & 0xFFFFFFFF for i in range(WORDS)]
    # The first words of each table, as Schneier's 1993 paper prints them.
    assert words[0] == 0x243F6A88 and words[17] == 0x8979FB1B
    assert words[18] == 0xD1310BA6 and words[18 + 256] == 0x4B7A70E9
    assert words[18 + 512] == 0xE93D5A68 and words[18 + 768] == 0x3A39CE37
    out = ["//! Blowfish's initial P-array and S-boxes: the hexadecimal digits of pi.",
           "//!",
           "//! Generated by `scripts/gen_blowfish_tables.py`, which computes pi with",
           "//! Machin's formula in integer arithmetic. Do not edit by hand.",
           "",
           "/// The P-array, 18 words.",
           "pub(super) const P: [u32; 18] = ["]
    out += [f"    0x{w:08x}," for w in words[:18]]
    out.append("];")
    out.append("")
    out.append("/// The four S-boxes, 256 words each.")
    out.append("pub(super) const S: [[u32; 256]; 4] = [")
    for box in range(4):
        out.append("    [")
        chunk = words[18 + 256 * box: 18 + 256 * (box + 1)]
        for i in range(0, 256, 4):
            out.append("        " + " ".join(f"0x{w:08x}," for w in chunk[i:i + 4]))
        out.append("    ],")
    out.append("];")
    print("\n".join(out))


if __name__ == "__main__":
    main()
