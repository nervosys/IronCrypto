"""Generate crates/ic-ec/src/nist/mont_x86.rs: Montgomery multiplication for
an arbitrary odd modulus of six 64-bit words, as one `asm!` block on
MULX/ADCX/ADOX, for P-384's two residue rings.

    python scripts/gen_mont_x86.py crates/ic-ec/src/nist/mont_x86.rs

CIOS, one row `a * b_i` and one Montgomery step at a time, both on two carry
chains: the low halves of the products on the carry flag (`adcx`), the high
halves on the overflow flag (`adox`). The modulus is read from a static
through a RIP-relative address and `-m^-1 mod 2^64` is an immediate, so the
block needs registers only for the window and the two operand pointers: eight
plus five, the thirteen the compiler leaves. It returns the window and its top
word, below 2m; the caller makes it canonical with one subtraction chosen
behind a barrier, as the generic multiplication does.
"""
import sys

N = 6


def mul(name):
    W = [f"{{w{i}}}" for i in range(N + 2)]
    out = []
    # Zero the window.
    for r in W[: N + 1]:
        out.append(f"xor {r[:-1]}:e}}, {r[:-1]}:e}}")
    for i in range(N):
        win = [W[(i + j) % (N + 2)] for j in range(N + 1)]  # t0..tN
        top = W[(i + N + 1) % (N + 2)]                    # new t_{N+1}
        out.append(f"// Row {i}: window += a * b{i}.")
        out.append(f"mov rdx, qword ptr [{{b}} + {8 * i}]")
        out.append(f"xor {top[:-1]}:e}}, {top[:-1]}:e}}")
        for j in range(N):
            off = f" + {8 * j}" if j else ""
            out += [
                f"mulx {{c}}, rax, qword ptr [{{a}}{off}]",
                f"adcx {win[j]}, rax",
                f"adox {win[j + 1]}, {{c}}",
            ]
        out += [
            "mov eax, 0",
            f"adcx {win[N]}, rax",
            f"adox {top}, rax",
            f"adcx {top}, rax",
        ]
        out.append(f"// Step: u = t0 * -m^-1, window += u * m; t0 becomes zero.")
        out += [
            "mov rdx, {ninv}",
            f"imul rdx, {win[0]}",
            "xor eax, eax",
        ]
        for j in range(N):
            off = f" + {8 * j}" if j else ""
            out += [
                f"mulx {{c}}, rax, qword ptr [rip + {{m}}{off}]",
                f"adcx {win[j]}, rax",
                f"adox {win[j + 1]}, {{c}}",
            ]
        out += [
            "mov eax, 0",
            f"adcx {win[N]}, rax",
            f"adox {top}, rax",
            f"adcx {top}, rax",
        ]
    final = [W[(N + j) % (N + 2)] for j in range(N + 1)]
    return out, final


def emit(name, static, doc):
    lines, final = mul(name)
    o = []
    o.append(f"/// {doc}")
    o.append("///")
    o.append("/// Returns the six words of `a * b * 2^-384 mod m`, not yet below `m`,")
    o.append("/// and the word above them; the value is below `2m`.")
    o.append("///")
    o.append("/// # Safety")
    o.append("///")
    o.append("/// The CPU must support BMI2 and ADX; see `super::p256_x86::has_adx`.")
    o.append("/// `a` and `b` must be below the modulus.")
    o.append("#[inline]")
    o.append(f"pub unsafe fn {name}(a: &[u64; {N}], b: &[u64; {N}]) -> ([u64; {N}], u64) {{")
    o.append(f"    let (r0, r1, r2, r3, r4, r5, top): (u64, u64, u64, u64, u64, u64, u64);")
    o.append("    // SAFETY: the caller guarantees the instructions exist. The block reads")
    o.append("    // the 48 bytes behind each of `a` and `b`, live references, and the")
    o.append(f"    // 48 bytes of `{static}`, a static; it writes only the registers it")
    o.append("    // declares and touches neither the stack nor memory.")
    o.append("    unsafe {")
    o.append("        asm!(")
    for l in lines:
        if l.startswith("//"):
            o.append(f"            {l}")
        else:
            o.append(f'            "{l}",')
    o.append("            a = in(reg) a.as_ptr(),")
    o.append("            b = in(reg) b.as_ptr(),")
    o.append(f"            m = sym {static},")
    o.append(f"            ninv = const neg_inv({static}_WORDS[0]),")
    names = {final[j]: f"r{j}" for j in range(N)}
    names[final[N]] = "top"
    for i in range(N + 2):
        reg = f"{{w{i}}}"
        if reg in names:
            o.append(f"            w{i} = out(reg) {names[reg]},")
        else:
            o.append(f"            w{i} = out(reg) _,")
    o.append("            c = out(reg) _,")
    o.append('            out("rax") _,')
    o.append('            out("rdx") _,')
    o.append("            options(pure, readonly, nostack),")
    o.append("        );")
    o.append("    }")
    o.append("    ([r0, r1, r2, r3, r4, r5], top)")
    o.append("}")
    return "\n".join(o)


HEADER = '''//! Montgomery multiplication modulo P-384's prime and group order, each one
//! `asm!` block over `mulx`/`adcx`/`adox`.
//!
//! GENERATED by `scripts/gen_mont_x86.py`; edit that, not this.
//!
//! The same function as the generic `arith::wide::mont_mul` up to its last
//! step, which the caller takes the same way: CIOS over six words with the
//! modulus read through a RIP-relative address. Nothing branches and nothing
//! is indexed by data. The tests hold both to the generic word loop.

use core::arch::asm;

/// `-m^-1 mod 2^64`, by Newton iteration, as `arith::compute_neg_inv`.
const fn neg_inv(m0: u64) -> u64 {
    let mut inv = m0;
    let mut i = 0;
    while i < 6 {
        inv = inv.wrapping_mul(2u64.wrapping_sub(m0.wrapping_mul(inv)));
        i += 1;
    }
    inv.wrapping_neg()
}

/// P-384's prime, little-endian.
const P384_P_WORDS: [u64; 6] = [
    0x0000_0000_ffff_ffff,
    0xffff_ffff_0000_0000,
    0xffff_ffff_ffff_fffe,
    0xffff_ffff_ffff_ffff,
    0xffff_ffff_ffff_ffff,
    0xffff_ffff_ffff_ffff,
];

/// P-384's group order, little-endian.
const P384_N_WORDS: [u64; 6] = [
    0xecec_196a_ccc5_2973,
    0x581a_0db2_48b0_a77a,
    0xc763_4d81_f437_2ddf,
    0xffff_ffff_ffff_ffff,
    0xffff_ffff_ffff_ffff,
    0xffff_ffff_ffff_ffff,
];

/// The prime, for the RIP-relative reads.
static P384_P: [u64; 6] = P384_P_WORDS;
/// The order, for the RIP-relative reads.
static P384_N: [u64; 6] = P384_N_WORDS;'''


def main():
    parts = [HEADER]
    parts.append(emit("mul_p384_p", "P384_P", "Montgomery multiplication modulo P-384's prime."))
    parts.append(emit("mul_p384_n", "P384_N", "Montgomery multiplication modulo P-384's group order."))
    text = "\n\n".join(parts) + "\n"
    with open(sys.argv[1], "w", encoding="utf-8", newline="\n") as f:
        f.write(text)


main()
